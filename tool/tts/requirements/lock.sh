#!/usr/bin/env bash
# Regenerates the hash-pinned requirement files for the voice tools (ADR-041).
#
#   tool/tts/requirements/lock.sh [YYYY-MM-DD]
#
# Needs uv (pip install uv, in a venv). Only versions published before the date
# are used (default: two weeks ago), for Python 3.11+ on every platform. One
# resolution of all the packages is the constraint for each group, so the
# groups always agree. torch comes only from the PyTorch CPU index.
set -euo pipefail
cd "$(dirname "$0")"
before=${1:-$(date -d '14 days ago' +%F)}
tmp=$(mktemp -d); trap 'rm -rf "$tmp"' EXIT
opts=(--universal --python-version 3.11 --generate-hashes --exclude-newer "$before" -q --no-header)

project() {  # project <dir> <dependencies...>
  mkdir -p "$1"; local deps; deps=$(printf '"%s", ' "${@:2}")
  cat > "$1/pyproject.toml" <<TOML
[project]
name = "tts-tools"
version = "0"
requires-python = ">=3.11"
dependencies = [${deps%, }]

[tool.uv.sources]
torch = { index = "pytorch-cpu" }

[[tool.uv.index]]
name = "pytorch-cpu"
url = "https://download.pytorch.org/whl/cpu"
explicit = true
TOML
}

project "$tmp/all" numpy soundfile lameenc kokoro-onnx moshi torch
uv pip compile "$tmp/all/pyproject.toml" "${opts[@]}" -o "$tmp/all.txt"
grep -E '^[a-z]' "$tmp/all.txt" | sed 's/ *\\$//' > "$tmp/constraints.txt"

group() {  # group <name> <packages...>
  project "$tmp/$1" "${@:2}"
  uv pip compile "$tmp/$1/pyproject.toml" "${opts[@]}" -c "$tmp/constraints.txt" -o "$tmp/$1.txt"
}
group base numpy soundfile lameenc
group kokoro kokoro-onnx
group kyutai moshi torch

# torch goes in its own file, installed from the PyTorch index only.
python3 - "$tmp" <<'PY'
import re, sys
tmp = sys.argv[1]
def blocks(path):
    out, cur = [], []
    for line in open(path):
        if re.match(r"[a-z]", line) and cur:
            out.append("".join(cur)); cur = []
        if re.match(r"[a-z]", line) or cur:
            cur.append(line)
    return out + (["".join(cur)] if cur else [])
head = lambda what: f"# {what}\n# Generated by tool/tts/requirements/lock.sh. Install with:\n#   pip install --require-hashes --no-deps -r <this file>\n"
for name, what in [("base", "Clip check and MP3 encoding"), ("kokoro", "Kokoro (EN/ES)")]:
    open(f"{name}.txt", "w").write(head(what) + "".join(blocks(f"{tmp}/{name}.txt")))
ky = blocks(f"{tmp}/kyutai.txt")
open("kyutai.txt", "w").write(head("Kyutai (FR), after torch.txt") + "".join(b for b in ky if not b.startswith("torch==")))
open("torch.txt", "w").write(
    "# CPU-only PyTorch for Kyutai. Generated by tool/tts/requirements/lock.sh. Install with:\n"
    "#   pip install --require-hashes --no-deps --index-url https://download.pytorch.org/whl/cpu -r <this file>\n"
    + "".join(b for b in ky if b.startswith("torch==")))
PY
echo "Locked with versions published before $before."
