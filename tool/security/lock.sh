#!/usr/bin/env bash
# Regenerates the hash-pinned requirements.txt for the scanners (ADR-042).
#
#   tool/security/lock.sh [YYYY-MM-DD]
#
# Needs uv (pip install uv, in a venv). Only versions published before the date
# are used (default: two weeks ago). overrides.txt forces security fixes.
set -euo pipefail
cd "$(dirname "$0")"
before=${1:-$(date -d '14 days ago' +%F)}
uv pip compile requirements.in --override overrides.txt --python-version 3.13 \
  --generate-hashes --exclude-newer "$before" -q --no-header -o requirements.txt
sed -i '1i # Generated by tool/security/lock.sh from requirements.in and overrides.txt.\n# Install with: pip install --require-hashes --no-deps -r tool/security/requirements.txt' requirements.txt
echo "Locked with versions published before $before."
